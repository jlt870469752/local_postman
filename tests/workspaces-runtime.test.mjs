import assert from 'node:assert/strict';
import { createBrowserInvoke, createRuntimeInvoke } from '../src/runtime.js';
const key = 'localpostman-workspace';
const original = { collections: [{ id: 'c', name: 'Original', items: [] }], environments: [{ id: 'e', values: { key: 'original' } }], history: [{ id: 'h' }], gitRepository: '/local/one' };
const entries = new Map([[key, JSON.stringify(original)]]);
let failedKey = null;
const storage = { getItem: name => entries.get(name) ?? null, setItem: (name, value) => { if (name === failedKey) throw Error('quota failure'); entries.set(name, value); } };
const browser = createBrowserInvoke({ storage });
assert.deepEqual(await browser('workspace_list'), [{ id: 'default', name: 'My Workspace', active: true }]);
assert.deepEqual(await browser('load_workspace'), original);
assert.equal(entries.get('localpostman-workspaces'), undefined, 'Legacy data is read without forcing migration writes');
const second = await browser('workspace_create', { name: '  New APIs  ' });
assert.equal(second.name, 'New APIs'); assert.equal(second.active, false);
assert.deepEqual(await browser('load_workspace'), original, 'Creating a workspace does not switch the active one');
assert.deepEqual(await browser('workspace_switch', { id: second.id }), { collections: [], environments: [], history: [] });
assert.equal((await browser('workspace_list')).find(item => item.active).id, second.id);
const other = { collections: [{ id: 'other', name: 'Independent', items: [] }], environments: [], history: [] };
await browser('save_workspace', { workspace: other });
assert.equal(entries.get(key), JSON.stringify(original), 'Saving another workspace never changes the original storage key');
await browser('workspace_rename', { id: second.id, name: 'Renamed APIs' });
assert.equal((await browser('workspace_list')).find(item => item.id === second.id).name, 'Renamed APIs');
await assert.rejects(browser('workspace_delete', { id: second.id }), /Switch to another/);
assert.deepEqual(await browser('workspace_switch', { id: 'default' }), original);
assert.deepEqual(await createBrowserInvoke({ storage })('load_workspace'), original, 'A new runtime restores active selection');
await browser('workspace_switch', { id: second.id });
assert.deepEqual(await createBrowserInvoke({ storage })('load_workspace'), other);
await browser('workspace_switch', { id: 'default' });
await browser('workspace_delete', { id: second.id });
assert.equal((await browser('workspace_list')).some(item => item.id === second.id), false);
assert.deepEqual(JSON.parse(entries.get(key + '-' + second.id)), other, 'Deleted data is retained as an archive');
await assert.rejects(browser('workspace_switch', { id: second.id }), /does not exist/);
for (const name of ['', '  ', 'x'.repeat(81)]) await assert.rejects(browser('workspace_create', { name }), /1–80/);
console.log('PASS: Browser workspace CRUD isolates data, preserves legacy key and restores active selection');

const third = await browser('workspace_create', { name: 'Failure case' });
const catalogBefore = entries.get('localpostman-workspaces');
entries.set(key + '-' + third.id, '{corrupt');
await assert.rejects(browser('workspace_switch', { id: third.id }));
assert.equal(entries.get('localpostman-workspaces'), catalogBefore, 'Invalid target data cannot change active workspace');
entries.set(key + '-' + third.id, JSON.stringify(other));
failedKey = 'localpostman-workspaces';
await assert.rejects(browser('workspace_switch', { id: third.id }), /quota failure/);
assert.equal(entries.get('localpostman-workspaces'), catalogBefore);
assert.deepEqual(await browser('load_workspace'), original, 'Catalog write failure leaves active storage routing unchanged');
failedKey = null;
entries.set('localpostman-workspaces', '{corrupt');
await assert.rejects(browser('workspace_list'));
await assert.rejects(browser('load_workspace'));
await assert.rejects(browser('save_workspace', { workspace: other }));
assert.equal(entries.get(key), JSON.stringify(original), 'Invalid catalog cannot redirect or overwrite legacy workspace');
console.log('PASS: Invalid targets, catalog corruption and failed selection writes cannot overwrite current data');

const calls = []; let release;
const runtime = createRuntimeInvoke({ isNative: () => true, browser, native: (command) => {
  calls.push(command); return command === 'save_workspace' ? new Promise(resolve => { release = resolve; }) : command;
} });
const save = runtime('save_workspace', { workspace: original });
const switched = runtime('workspace_switch', { id: third.id });
await Promise.resolve(); assert.deepEqual(calls, ['save_workspace']);
release(); await save; assert.equal(await switched, 'workspace_switch');
assert.deepEqual(calls, ['save_workspace', 'workspace_switch'], 'Native switching waits for pending saves');
console.log('PASS: Native workspace switching waits for pending writes');
